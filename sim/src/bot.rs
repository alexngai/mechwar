//! Server-side bot brain. A bot only produces an `Input` each tick; `Game` applies it through
//! `step_mech` and the normal hitscan, so bots follow the same rules as players.

use std::collections::VecDeque;
use std::f32::consts::{PI, TAU};
use std::sync::OnceLock;

use libm::{asinf, atan2f, hypotf};
use rapier3d::prelude::{Ray, Rotation};

use crate::item;
use crate::map::{MAPS, Map};
use crate::{Arena, DT, Input, Mech, MechClass, TICK_HZ, Tuning, Vector, spawn_mech, step_mech};

/// A waypoint links to another this close when a mech can walk there.
const LINK_RANGE: f32 = 35.0;

/// A map's bot waypoints, with edges generated by walking: a waypoint links to each within
/// `LINK_RANGE` that a Heavy (the widest class) steering straight at it reaches in time.
/// Edges are one-way, so a ledge gives a drop where there's no climb back.
pub struct Nav {
    nodes: Vec<Vector>,
    /// (from, to).
    edges: Vec<(usize, usize)>,
}

impl Nav {
    /// Generated once per compiled-in map and cached.
    pub fn for_map(index: usize) -> &'static Nav {
        static CACHE: [OnceLock<Nav>; MAPS.len()] = [const { OnceLock::new() }; MAPS.len()];
        CACHE[index].get_or_init(|| {
            let map = Map::load(index);
            Nav::generate(&Arena::new(&map), &map.nav, &Tuning::default().for_class(MechClass::C))
        })
    }

    pub fn generate(arena: &Arena, points: &[[f32; 3]], t: &Tuning) -> Nav {
        let nodes: Vec<Vector> = points.iter().map(|p| Vector::from_array(*p)).collect();
        // A jump pad's waypoint links to its landing however far the pad throws.
        let thrown = |a: Vector, b: Vector| {
            arena.pads.iter().any(|p| Vector::from_array(p.at).distance(a) < 0.5 && Vector::from_array(p.to).distance(b) < 0.5)
        };
        let mut edges = Vec::new();
        for a in 0..nodes.len() {
            for b in 0..nodes.len() {
                let (na, nb) = (nodes[a], nodes[b]);
                if a != b && (na.distance(nb) <= LINK_RANGE || thrown(na, nb)) && walkable(arena, t, na, nb) {
                    edges.push((a, b));
                }
            }
        }
        Nav { nodes, edges }
    }

    fn node(&self, i: usize) -> Vector {
        self.nodes[i]
    }

    /// The closest waypoint in clear view of `p` (else the closest at all), counting height
    /// triple: one across a wall, or up on the deck overhead, is no place to start walking from.
    pub fn nearest(&self, arena: &Arena, p: Vector) -> usize {
        let cost = |i: usize| ((self.nodes[i] - p) * Vector::new(1.0, 3.0, 1.0)).length();
        let mut order: Vec<usize> = (0..self.nodes.len()).collect();
        order.sort_by(|&a, &b| cost(a).total_cmp(&cost(b)));
        let clear = |i: usize| {
            let (from, d) = (p + Vector::Y * 1.5, self.nodes[i] - p);
            d.length() < 0.1 || arena.cast_ray(&Ray::new(from, d / d.length()), d.length()).is_none()
        };
        order.iter().copied().find(|&i| clear(i)).unwrap_or(order[0])
    }

    /// Which waypoints can be reached from `from`.
    pub fn reachable(&self, from: usize) -> Vec<bool> {
        let mut seen = vec![false; self.nodes.len()];
        let mut stack = vec![from];
        while let Some(u) = stack.pop() {
            if std::mem::replace(&mut seen[u], true) {
                continue;
            }
            stack.extend(self.edges.iter().filter(|&&(a, _)| a == u).map(|&(_, b)| b));
        }
        seen
    }

    /// Shortest waypoint route from `from` to whichever waypoint `pick` chooses given every
    /// waypoint's route cost (f32::MAX if unreachable), both ends included (Dijkstra; the graph
    /// is small).
    fn path(&self, from: usize, pick: impl FnOnce(&[f32]) -> usize) -> Vec<usize> {
        let n = self.nodes.len();
        let (mut dist, mut prev, mut done) = (vec![f32::MAX; n], vec![usize::MAX; n], vec![false; n]);
        dist[from] = 0.0;
        while let Some(u) = (0..n).filter(|&i| !done[i] && dist[i] < f32::MAX).min_by(|&a, &b| dist[a].total_cmp(&dist[b])) {
            done[u] = true;
            for &(_, v) in self.edges.iter().filter(|&&(a, _)| a == u) {
                let d = dist[u] + self.node(u).distance(self.node(v));
                if d < dist[v] {
                    dist[v] = d;
                    prev[v] = u;
                }
            }
        }
        let mut route = vec![pick(&dist)];
        while let Some(&last) = route.last()
            && prev[last] != usize::MAX
        {
            route.push(prev[last]);
        }
        route.reverse();
        route
    }

    /// The reachable waypoint that `rank` scores lowest, given its index and route cost (None
    /// rules it out).
    fn vantage(&self, cost: &[f32], rank: impl Fn(usize, f32) -> Option<f32>) -> Option<usize> {
        (0..self.nodes.len())
            .filter(|&i| cost[i] < f32::MAX)
            .filter_map(|i| Some((i, rank(i, cost[i])?)))
            .min_by(|a, b| a.1.total_cmp(&b.1))
            .map(|(i, _)| i)
    }

    /// A mech standing on waypoint `i` would see `target` within VANTAGE_RANGE.
    fn overlooks(&self, arena: &Arena, t: &Tuning, i: usize, target: &Mech) -> bool {
        self.nodes[i].distance(target.pos) < VANTAGE_RANGE && sees(arena, t, &Mech { pos: self.nodes[i], ..Mech::default() }, target)
    }

    /// Side lanes run this far out along x: the maps put their bases at ±z.
    fn lane_x(&self) -> f32 {
        0.6 * self.nodes.iter().fold(0.0, |m, n| n.x.abs().max(m))
    }
}

/// A mech starting at `from` and steering straight at `to` arrives within distance / walk speed + 2 s.
fn walkable(arena: &Arena, t: &Tuning, from: Vector, to: Vector) -> bool {
    let mut m = spawn_mech(t, from + Vector::Y * 0.1);
    let ticks = ((to.distance(from) / t.walk_speed + 2.0) * TICK_HZ) as usize;
    (0..ticks).any(|_| {
        let d = to - m.pos;
        if flat(d).length() < ARRIVE && d.y.abs() < 1.0 {
            return true;
        }
        step_mech(arena, t, &mut m, &Input { move_z: 1.0, yaw: atan2f(-d.x, -d.z), ..Input::default() });
        false
    })
}

/// Waypoint counts as reached within this horizontal distance.
const ARRIVE: f32 = 2.5;
/// Bots boost toward a waypoint at least this far away.
const BOOST_LEG: f32 = 15.0;
/// Engagement range band: close in beyond FAR, back off inside NEAR.
const FAR: f32 = 45.0;
const NEAR: f32 = 20.0;
/// Fire only when aim is this close to where the bot wants it.
const AIM_TOLERANCE: f32 = 2.0 * PI / 180.0;
/// Farthest a Heavy lobs its grenade launcher's shells.
const MORTAR_RANGE: f32 = 40.0;
/// Farthest a bot lobs a grenade (short of its flat-ground reach).
const GRENADE_RANGE: f32 = 28.0;
/// Farthest a perch may be from the target.
const VANTAGE_RANGE: f32 = 75.0;
/// Flankers and sneaks take the long way only to a target farther off than this.
const DETOUR_MIN: f32 = 60.0;

/// How a bot goes after its target this life.
#[derive(Clone, Copy, PartialEq)]
enum Role {
    /// Straight at it.
    Hunt,
    /// Up to a deck or gantry overlooking it, to hold there and fire down.
    Perch,
    /// Round through the side lane on this side of x (±1), then in.
    Flank(f32),
    /// Through a sunken channel (waypoints below the ground), then in.
    Sneak,
}

pub struct Bot {
    pub seq: u32,
    rng: u64,
    role: Role,
    /// Remaining waypoints, next first, toward `vantage` or else the target's waypoint `path_goal`.
    path: Vec<usize>,
    path_goal: Option<usize>,
    vantage: Option<usize>,
    /// Closest the bot has come to the next waypoint, and when it last got closer.
    best: f32,
    progress_at: u32,
    hover_until: u32,
    strafe: f32,
    strafe_until: u32,
    /// Slowly wandering aim error (yaw, pitch) in radians.
    wobble: (f32, f32),
    /// Target chest positions, oldest first, so aim lags by the reaction time.
    seen: VecDeque<Vector>,
    last_health: f32,
    /// No grenade before this tick, so charges go one every few seconds.
    grenade_at: u32,
    /// Holding fire to cool: set near the overheat lockout, cleared once heat is well down.
    cooling: bool,
}

impl Bot {
    pub fn new(seed: u64) -> Self {
        let mut bot = Self {
            seq: 0,
            rng: seed.wrapping_mul(0x9E37_79B9_7F4A_7C15) | 1,
            role: Role::Hunt,
            path: Vec::new(),
            path_goal: None,
            vantage: None,
            best: f32::MAX,
            progress_at: 0,
            hover_until: 0,
            strafe: 1.0,
            strafe_until: 0,
            wobble: (0.0, 0.0),
            seen: VecDeque::new(),
            last_health: 0.0,
            grenade_at: 0,
            cooling: false,
        };
        bot.respawned();
        bot
    }

    /// A fresh life: a new role, and a route planned from wherever it starts.
    pub fn respawned(&mut self) {
        let r = self.rand();
        let side = if self.rand() < 0.5 { -1.0 } else { 1.0 };
        self.role = if r < 0.4 {
            Role::Hunt
        } else if r < 0.7 {
            Role::Perch
        } else if r < 0.9 {
            Role::Flank(side)
        } else {
            Role::Sneak
        };
        (self.path_goal, self.vantage) = (None, None);
        self.cooling = false;
    }

    /// xorshift64, uniform in [0, 1).
    fn rand(&mut self) -> f32 {
        self.rng ^= self.rng << 13;
        self.rng ^= self.rng >> 7;
        self.rng ^= self.rng << 17;
        (self.rng >> 40) as f32 / (1u64 << 24) as f32
    }

    /// This tick's input for a bot driving `me` against `target`.
    pub fn think(&mut self, arena: &Arena, nav: &Nav, t: &Tuning, me: &Mech, target: Option<&Mech>, tick: u32) -> Input {
        let idle = Input { yaw: me.yaw, pitch: me.pitch, ..Input::default() };
        let took_damage = me.health < self.last_health;
        self.last_health = me.health;
        if me.health <= 0.0 {
            self.respawned();
            return idle;
        }
        let Some(target) = target.filter(|m| m.health > 0.0) else {
            self.seen.clear();
            return idle;
        };

        self.seen.push_back(target.pos + Vector::Y * (t.mech_height * 0.5));
        let reaction_ticks = (t.bot_reaction_s * TICK_HZ).round() as usize;
        while self.seen.len() > reaction_ticks + 1 {
            self.seen.pop_front();
        }
        let max_turn = t.bot_turn_rate_deg.to_radians() * DT;
        let range = flat(target.pos - me.pos).length();

        if sees(arena, t, me, target) {
            let err = t.bot_aim_error_deg.to_radians();
            self.wobble.0 = (self.wobble.0 + (self.rand() - 0.5) * err * 0.3).clamp(-err, err);
            self.wobble.1 = (self.wobble.1 + (self.rand() - 0.5) * err * 0.3).clamp(-err, err);
            // The secondary, when ready and in its useful range, takes over the aim until it fires:
            // led by the flight time, and lobbed along the flat-ground arc for the mortar. The gun
            // holds meanwhile, so heat drops enough for the launch not to overheat.
            let (eye, chest) = (me.pos + Vector::Y * t.eye_height, self.seen[0]);
            let dist = chest.distance(eye);
            let alt_range = if t.alt_gravity > 0.0 { MORTAR_RANGE } else { 0.8 * t.alt_speed * t.alt_fuse };
            let alt = me.alt_wait <= 0.0 && dist < alt_range && dist > t.alt_radius + 2.0;
            let alt_cool = !me.overheated && me.heat + t.alt_heat < t.heat_max;
            // Otherwise a grenade takes the aim the same way, every few seconds while charges last.
            let grenade = t.grenade();
            let throw = !alt && me.grenades > 0 && tick >= self.grenade_at && dist < GRENADE_RANGE && dist > t.grenade_radius + 2.0;
            let shell = if alt { Some(t) } else if throw { Some(&grenade) } else { None };
            // Shells are led by their flight time, and so are projectile primaries.
            let primary_lead = if t.shot_speed > 0.0 { dist / t.shot_speed } else { 0.0 };
            let lead = shell.map_or(primary_lead, |s| dist / s.alt_speed);
            let (yaw, mut pitch) = look_at(eye, chest + target.vel * lead);
            if let Some(s) = shell
                && s.alt_gravity > 0.0
            {
                // Range d on flat ground: sin(2θ) = g d / v².
                let r = (s.alt_gravity * flat(chest - eye).length() / (s.alt_speed * s.alt_speed)).min(1.0);
                pitch = 0.5 * asinf(r) - s.alt_loft_deg.to_radians();
            }
            let (want_yaw, want_pitch) = (yaw + self.wobble.0, pitch + self.wobble.1);
            let new_yaw = me.yaw + wrap(want_yaw - me.yaw).clamp(-max_turn, max_turn);
            let new_pitch = me.pitch + (want_pitch - me.pitch).clamp(-max_turn, max_turn);
            let on_target = wrap(want_yaw - new_yaw).abs() < AIM_TOLERANCE && (want_pitch - new_pitch).abs() < AIM_TOLERANCE;

            if tick >= self.strafe_until {
                self.strafe = if self.rand() < 0.5 { -1.0 } else { 1.0 };
                self.strafe_until = tick + secs(0.8 + 1.2 * self.rand());
            }
            let dodge = took_damage && me.dodge_cooldown <= 0.0 && self.rand() < 0.3;
            // Fire in bursts: stop near the lockout and let heat fall well down (it sheds fastest
            // low) before firing again.
            if me.overheated || me.heat >= 0.85 * t.heat_max {
                self.cooling = true;
            } else if me.heat <= 0.4 * t.heat_max {
                self.cooling = false;
            }
            let throw = throw && on_target;
            if throw {
                self.grenade_at = tick + secs(4.0 + 4.0 * self.rand());
            }
            // Far off, keep walking the route (firing on the way) rather than straight at the
            // target: on a tiered map that keeps bots on their ramps and decks, not off ledges.
            // Perches keep climbing to their vantage too, then hold it, and a bot cooling off
            // repositions along its route. In range, hold the band and strafe.
            let perch = self.role == Role::Perch && self.vantage.is_some();
            let (move_x, move_z) = if range > FAR || perch || self.cooling {
                let dir = self.route(arena, nav, t, me, target, tick).normalize_or_zero();
                let rot = Rotation::from_rotation_y(new_yaw);
                (dir.dot(rot * Vector::X), dir.dot(rot * Vector::NEG_Z))
            } else {
                (self.strafe, if range < NEAR { -1.0 } else { 0.0 })
            };
            return Input {
                move_x,
                move_z,
                yaw: new_yaw,
                pitch: new_pitch,
                dodge: if dodge && !self.perched(nav, me) { self.strafe as i8 } else { 0 },
                fire: shell.is_none() && on_target && !self.cooling,
                alt_fire: alt && alt_cool && on_target,
                grenade: throw,
                hover: tick < self.hover_until,
                // When it would land (taking the target for our size), and they aren't jammed already.
                emp: me.emps > 0 && target.jammed <= 0.0 && item::emp_reaches(arena, t, me, t, target),
                // Mediums vent before stalling; Heavies raise their bulwark once hurt and under fire.
                ability: match me.class {
                    MechClass::B => me.overheated || me.heat >= 0.8 * t.heat_max,
                    MechClass::C => took_damage && me.health < 0.6 * t.health_max,
                    MechClass::A => false,
                },
                ..Input::default()
            };
        }

        // No line of sight: walk the waypoint graph toward the target.
        let toward = self.route(arena, nav, t, me, target, tick);
        let dir = toward.normalize_or_zero();
        let want_yaw = atan2f(-dir.x, -dir.z);
        let new_yaw = me.yaw + wrap(want_yaw - me.yaw).clamp(-max_turn, max_turn);
        let rot = Rotation::from_rotation_y(new_yaw);
        Input {
            move_x: dir.dot(rot * Vector::X),
            move_z: dir.dot(rot * Vector::NEG_Z),
            yaw: new_yaw,
            pitch: me.pitch * 0.9,
            // Boost on long legs only: at boost speed a bot overshoots turns onto ramps.
            boost: range > FAR && me.fuel > 0.5 * t.fuel_max && toward.length() > BOOST_LEG,
            // Lights speed boost on long runs.
            ability: me.class == MechClass::A && range > FAR,
            hover: tick < self.hover_until,
            // Hurt and out of sight: stop and repair until full or seen again.
            repair: me.repair_time > 0.0 || me.health < 0.3 * t.health_max,
            ..Input::default()
        }
    }

    /// Follows the waypoint route toward `target` (by way of a vantage, for perches, flankers and
    /// sneaks), replanning when the target moves to another waypoint out of the vantage's view;
    /// returns the flat offset to the next waypoint (or the vantage, or the target, past the last).
    fn route(&mut self, arena: &Arena, nav: &Nav, t: &Tuning, me: &Mech, target: &Mech, tick: u32) -> Vector {
        let goal = nav.nearest(arena, target.pos);
        let moved = self.path_goal != Some(goal) && !self.vantage.is_some_and(|v| nav.overlooks(arena, t, v, target));
        // Perched where it can't see the target after all: go straight at it instead.
        let blind = self.perched(nav, me) && !sees(arena, t, me, target);
        if self.path_goal.is_none() || moved || blind {
            let (role, lane, far) = (self.role, nav.lane_x(), me.pos.distance(target.pos) > DETOUR_MIN);
            let (at, from_target) = (|i| nav.node(i), |i| nav.node(i).distance(target.pos));
            let mut vantage = None;
            self.path = nav.path(nav.nearest(arena, me.pos), |cost| {
                vantage = match role {
                    _ if blind => None,
                    // A perch in view of the target, near both, each metre up worth 4 of walking;
                    // the spot out in the side lane level with it, to come at it side-on; the
                    // channel spot nearest it.
                    Role::Perch => nav.vantage(cost, |i, c| (at(i).y > 2.0 && nav.overlooks(arena, t, i, target)).then(|| c + from_target(i) - 4.0 * at(i).y)),
                    Role::Flank(side) if far => nav.vantage(cost, |i, _| (at(i).x * side > lane).then(|| (at(i).z - target.pos.z).abs())),
                    Role::Sneak if far => nav.vantage(cost, |i, _| (at(i).y < -1.0).then(|| from_target(i))),
                    _ => None,
                };
                vantage.unwrap_or(goal)
            });
            self.vantage = vantage;
            // Already past the first waypoint toward the second? Skip it rather than walk back.
            if let [a, b, ..] = self.path[..]
                && me.pos.distance(nav.node(b)) < nav.node(a).distance(nav.node(b))
            {
                self.path.remove(0);
            }
            self.path_goal = Some(goal);
            self.best = f32::MAX;
            self.progress_at = tick;
        }
        while let Some(&n) = self.path.first()
            && flat(nav.node(n) - me.pos).length() < ARRIVE
            && (nav.node(n).y - me.pos.y).abs() < 2.0
        {
            self.path.remove(0);
            self.best = f32::MAX;
            self.progress_at = tick;
        }
        // A flanker or sneak in position goes in.
        if self.path.is_empty() && matches!(self.role, Role::Flank(_) | Role::Sneak) && self.vantage.is_some() {
            (self.role, self.vantage, self.path_goal) = (Role::Hunt, None, None);
        }
        if self.perched(nav, me) {
            return Vector::ZERO;
        }
        let toward = flat(self.path.first().copied().or(self.vantage).map_or(target.pos, |n| nav.node(n)) - me.pos);
        // Stuck on something for 1.5 s: hover over it and skip the waypoint, or plan again from
        // here if it's on another level (knocked off a deck, say) or the last.
        if toward.length() < self.best - 0.5 {
            self.best = toward.length();
            self.progress_at = tick;
        } else if tick - self.progress_at > secs(1.5) && !me.pad_arc {
            self.hover_until = tick + secs(1.0);
            match self.path.first() {
                Some(&n) if (nav.node(n).y - me.pos.y).abs() < 2.0 => _ = self.path.remove(0),
                _ => self.path_goal = None,
            }
            self.best = f32::MAX;
            self.progress_at = tick;
        }
        toward
    }

    /// Standing on its vantage as a perch, to hold it.
    fn perched(&self, nav: &Nav, me: &Mech) -> bool {
        self.role == Role::Perch
            && self.path.is_empty()
            && self.vantage.is_some_and(|v| flat(nav.node(v) - me.pos).length() < ARRIVE && (nav.node(v).y - me.pos.y).abs() < 2.0)
    }
}

/// Clear line from `me`'s eye to `target`'s chest, within weapon range.
pub fn sees(arena: &Arena, t: &Tuning, me: &Mech, target: &Mech) -> bool {
    let eye = me.pos + Vector::Y * t.eye_height;
    let d = target.pos + Vector::Y * (t.mech_height * 0.5) - eye;
    let len = d.length();
    len <= t.weapon_range && arena.cast_ray(&Ray::new(eye, d / len), len).is_none()
}

fn flat(v: Vector) -> Vector {
    Vector::new(v.x, 0.0, v.z)
}

/// Yaw and pitch that point from `from` at `to`, matching `aim_ray`.
fn look_at(from: Vector, to: Vector) -> (f32, f32) {
    let d = to - from;
    (atan2f(-d.x, -d.z), atan2f(d.y, hypotf(d.x, d.z)))
}

fn wrap(angle: f32) -> f32 {
    (angle + PI).rem_euclid(TAU) - PI
}

fn secs(s: f32) -> u32 {
    (s * TICK_HZ).round() as u32
}

