/// How a bot works its secondary, read off the weapon's stats so it follows any retuning.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) enum AltUse {
    /// Shells at the target, led by their flight and lobbed when they drop (mines too).
    Shell,
    /// A beam held on the target (`alt_beam`).
    Beam,
    /// Lock with `aux`, then fire once it holds (`alt_lock_time`).
    Lock,
    /// Pressed, then let go to fire (`alt_release`).
    Release,
    /// Fed by heat: fired once the mech runs hot (`alt_heat_fed`).
    HeatFed,
    /// Wound up near the target, then let go to lunge and strike (`alt_melee`).
    Melee,
}

pub(crate) fn alt_use(t: &Tuning) -> AltUse {
    if t.alt_beam > 0.0 {
        AltUse::Beam
    } else if t.alt_lock_time > 0.0 {
        AltUse::Lock
    } else if t.alt_heat_fed > 0.0 {
        AltUse::HeatFed
    } else if t.alt_melee > 0.0 {
        AltUse::Melee
    } else if t.alt_release > 0.0 {
        AltUse::Release
    } else {
        AltUse::Shell
    }
}

/// The distance a bot carrying `t` likes to fight at: where its primary still hits hard (a
/// projectile's, where its flight is still short enough to lead and well short of its fuse).
fn preferred_range(t: &Tuning) -> f32 {
    let reach = if t.shot_speed > 0.0 {
        let fused = if t.shot_fuse > 0.0 { 0.8 * t.shot_speed * t.shot_fuse } else { t.weapon_range };
        t.weapon_range.min(0.6 * t.shot_speed).min(fused)
    } else {
        t.falloff_start.min(t.weapon_range)
    };
    reach.clamp(10.0, 60.0)
}

/// Engagement band around the preferred range: close in beyond `.1`, back off inside `.0`. A
/// rocket punch's carrier fights inside half its lunge: a full one's flight is long enough for a
/// target on the move to slip it.
fn band(t: &Tuning, p: &Policy) -> (f32, f32) {
    if alt_use(t) == AltUse::Melee {
        let r = preferred_range(t).min(0.5 * t.alt_lunge);
        return (p.band_near * r, r);
    }
    let r = preferred_range(t);
    (p.band_near * r, p.band_far * r)
}

/// Whether a pile driver wound `charge` (0-1) and let go now lunges onto `target`: in the lunge's
/// reach with nothing in the way (low cover it sees over would stop the dash), and the target not
/// moving off more than the strike reaches in the time the lunge takes to get where it stands (a
/// dash a dodge's drag eases off, as `melee::lunge`'s).
fn lunge_lands(arena: &Arena, t: &Tuning, me: &Mech, target: &Mech, charge: f32) -> bool {
    let gap = (flat(target.pos - me.pos).length() - 2.0 * t.mech_radius).max(0.0);
    let flight = (2.0 * gap / t.dodge_drag.max(1.0)).sqrt();
    // Along both flanks of the hull, so it doesn't clip a corner.
    let d = target.pos - me.pos;
    let side = Vector::new(-d.z, 0.0, d.x).normalize_or_zero() * t.mech_radius;
    let clear = || [side, -side].iter().all(|&s| arena.cast_ray(&Ray::new(me.pos + s + Vector::Y * (0.3 * t.mech_height), d.normalize_or_zero()), d.length()).is_none());
    gap <= t.alt_lunge * charge && flat(target.vel).length() * flight <= t.alt_melee && clear()
}

/// Guardrails on a random build: a repair torch wants a gun that reaches well past its beam (it
/// heals from behind the fight), a heat-fed launcher a gun that runs hot enough to feed it, a
/// rail gun more than a shotgun's reach to share its fight with, and a pile driver a gun that
/// fights close enough to get it in reach.
fn sensible(t: &Tuning) -> bool {
    let heat_per_s = t.heat_per_shot * t.burst.max(1.0) * t.fire_rate;
    match alt_use(t) {
        AltUse::Beam => preferred_range(t) >= 30.0,
        AltUse::HeatFed => heat_per_s >= 20.0,
        AltUse::Release => preferred_range(t) >= 25.0,
        AltUse::Melee => preferred_range(t) <= 30.0,
        _ => true,
    }
}

