/// A waypoint links to another this close when a mech can walk there.
const LINK_RANGE: f32 = 35.0;

/// A map's bot waypoints, with edges generated by walking: a waypoint links to each within
/// `LINK_RANGE` that a Heavy (the widest class) steering straight at it reaches in time.
/// Edges are one-way, so a ledge gives a drop where there's no climb back.
pub struct Nav {
    nodes: Vec<Vector>,
    /// (from, to).
    edges: Vec<(usize, usize)>,
}

/// Each map's edges as `bake_nav` (in the tests below) walked them, with a hash of the map they
/// came from. Walking takes seconds per map (more on terrain): too long for a server waking up
/// to a visitor, or a page starting offline practice. The deploy bakes it fresh (see the
/// Dockerfile); a map changed since the committed bake just walks here, slower, until it's
/// re-baked: `cargo test -p sim --release --lib bake_nav -- --ignored`.
const BAKED: &str = include_str!("../../maps/nav.json");

#[derive(Serialize, Deserialize)]
struct Baked {
    source: String,
    edges: Vec<(usize, usize)>,
}

/// FNV-1a of a map's JSON: the same on every build.
fn source_hash(json: &str) -> String {
    format!("{:016x}", json.bytes().fold(0xcbf2_9ce4_8422_2325_u64, |h, b| (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3)))
}

impl Nav {
    /// Baked for each compiled-in map (walked here if the map has changed since), and cached.
    pub fn for_map(index: usize) -> &'static Nav {
        static CACHE: [OnceLock<Nav>; MAPS.len()] = [const { OnceLock::new() }; MAPS.len()];
        CACHE[index].get_or_init(|| match Nav::baked(BAKED, index) {
            Some(edges) => Nav { nodes: Map::load(index).nav.iter().map(|p| Vector::from_array(*p)).collect(), edges },
            None => Nav::walk_map(index),
        })
    }

    /// Map `index`'s edges from `bakes` (maps/nav.json's form), if baked from the map as it is.
    fn baked(bakes: &str, index: usize) -> Option<Vec<(usize, usize)>> {
        let (name, json) = MAPS[index];
        let mut bakes: BTreeMap<String, Baked> = serde_json::from_str(bakes).expect("maps/nav.json is valid");
        bakes.remove(name).filter(|b| b.source == source_hash(json)).map(|b| b.edges)
    }

    fn walk_map(index: usize) -> Nav {
        let map = Map::load(index);
        Nav::generate(&Arena::new(&map), &map.nav, &Tuning::default().for_class(MechClass::C))
    }

    pub fn generate(arena: &Arena, points: &[[f32; 3]], t: &Tuning) -> Nav {
        let nodes: Vec<Vector> = points.iter().map(|p| Vector::from_array(*p)).collect();
        // A jump pad's waypoint links to its landing however far the pad throws.
        let thrown = |a: Vector, b: Vector| {
            arena.pads.iter().any(|p| Vector::from_array(p.at).distance(a) < 0.5 && Vector::from_array(p.to).distance(b) < 0.5)
        };
        let mut edges = Vec::new();
        for a in 0..nodes.len() {
            for b in 0..nodes.len() {
                let (na, nb) = (nodes[a], nodes[b]);
                if a != b && (na.distance(nb) <= LINK_RANGE || thrown(na, nb)) && walkable(arena, t, na, nb) {
                    edges.push((a, b));
                }
            }
        }
        Nav { nodes, edges }
    }

    fn node(&self, i: usize) -> Vector {
        self.nodes[i]
    }

    /// The closest waypoint in clear view of `p` (else the closest at all), counting height
    /// triple: one across a wall, or up on the deck overhead, is no place to start walking from.
    pub fn nearest(&self, arena: &Arena, p: Vector) -> usize {
        let cost = |i: usize| ((self.nodes[i] - p) * Vector::new(1.0, 3.0, 1.0)).length();
        let mut order: Vec<usize> = (0..self.nodes.len()).collect();
        order.sort_by(|&a, &b| cost(a).total_cmp(&cost(b)));
        let clear = |i: usize| {
            let (from, d) = (p + Vector::Y * 1.5, self.nodes[i] - p);
            d.length() < 0.1 || arena.cast_ray(&Ray::new(from, d / d.length()), d.length()).is_none()
        };
        order.iter().copied().find(|&i| clear(i)).unwrap_or(order[0])
    }

    /// Which waypoints can be reached from `from`.
    pub fn reachable(&self, from: usize) -> Vec<bool> {
        let mut seen = vec![false; self.nodes.len()];
        let mut stack = vec![from];
        while let Some(u) = stack.pop() {
            if std::mem::replace(&mut seen[u], true) {
                continue;
            }
            stack.extend(self.edges.iter().filter(|&&(a, _)| a == u).map(|&(_, b)| b));
        }
        seen
    }

    /// Shortest waypoint route from `from` to whichever waypoint `pick` chooses given every
    /// waypoint's route cost (f32::MAX if unreachable), both ends included (Dijkstra; the graph
    /// is small).
    fn path(&self, from: usize, pick: impl FnOnce(&[f32]) -> usize) -> Vec<usize> {
        let n = self.nodes.len();
        let (mut dist, mut prev, mut done) = (vec![f32::MAX; n], vec![usize::MAX; n], vec![false; n]);
        dist[from] = 0.0;
        while let Some(u) = (0..n).filter(|&i| !done[i] && dist[i] < f32::MAX).min_by(|&a, &b| dist[a].total_cmp(&dist[b])) {
            done[u] = true;
            for &(_, v) in self.edges.iter().filter(|&&(a, _)| a == u) {
                let d = dist[u] + self.node(u).distance(self.node(v));
                if d < dist[v] {
                    dist[v] = d;
                    prev[v] = u;
                }
            }
        }
        let mut route = vec![pick(&dist)];
        while let Some(&last) = route.last()
            && prev[last] != usize::MAX
        {
            route.push(prev[last]);
        }
        route.reverse();
        route
    }

    /// The reachable waypoint that `rank` scores lowest, given its index and route cost (None
    /// rules it out).
    fn vantage(&self, cost: &[f32], rank: impl Fn(usize, f32) -> Option<f32>) -> Option<usize> {
        (0..self.nodes.len())
            .filter(|&i| cost[i] < f32::MAX)
            .filter_map(|i| Some((i, rank(i, cost[i])?)))
            .min_by(|a, b| a.1.total_cmp(&b.1))
            .map(|(i, _)| i)
    }

    /// The waypoint nearest by route from `from`, within `reach` of it, where a mech's chest is
    /// hidden from `threat` (another mech's eye).
    fn cover(&self, arena: &Arena, t: &Tuning, from: usize, threat: Vector, reach: f32) -> Option<usize> {
        let hidden = |i: usize| {
            let d = self.nodes[i] + Vector::Y * (t.mech_height * 0.5) - threat;
            arena.cast_ray(&Ray::new(threat, d / d.length()), d.length()).is_some()
        };
        let mut found = None;
        self.path(from, |cost| {
            found = (0..cost.len()).filter(|&i| cost[i] <= reach && hidden(i)).min_by(|&a, &b| cost[a].total_cmp(&cost[b]));
            found.unwrap_or(from)
        });
        found
    }

    /// A mech standing on waypoint `i` would see `target` within VANTAGE_RANGE.
    fn overlooks(&self, arena: &Arena, t: &Tuning, i: usize, target: &Mech) -> bool {
        self.nodes[i].distance(target.pos) < VANTAGE_RANGE && sees(arena, t, &Mech { pos: self.nodes[i], ..Mech::default() }, target)
    }

    /// Side lanes run this far out along x: the maps put their bases at ±z.
    fn lane_x(&self) -> f32 {
        0.6 * self.nodes.iter().fold(0.0, |m, n| n.x.abs().max(m))
    }
}

/// A mech starting at `from` and steering straight at `to` arrives within distance / walk speed + 2 s.
/// One that gets no half metre closer in 1.5 s is stuck, which is how most walks fail: it gives up then.
fn walkable(arena: &Arena, t: &Tuning, from: Vector, to: Vector) -> bool {
    let mut m = spawn_mech(t, from + Vector::Y * 0.1);
    let ticks = ((to.distance(from) / t.walk_speed + 2.0) * TICK_HZ) as usize;
    let (mut closest, mut stuck) = (f32::MAX, 0);
    for _ in 0..ticks {
        let d = to - m.pos;
        let left = flat(d).length();
        if left < ARRIVE && d.y.abs() < 1.0 {
            return true;
        }
        if left < closest - 0.5 {
            (closest, stuck) = (left, 0);
        } else if stuck > (1.5 * TICK_HZ) as usize {
            return false;
        } else {
            stuck += 1;
        }
        step_mech(arena, t, &mut m, &Input { move_z: 1.0, yaw: atan2f(-d.x, -d.z), ..Input::default() });
    }
    false
}

